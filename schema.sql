-- Run this in the skillsync database on Amazon RDS PostgreSQL.
-- Creates empty tables compatible with the adapted SkillSync backend.
CREATE TABLE IF NOT EXISTS users (
  user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) UNIQUE NOT NULL,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL,
  cgpa NUMERIC(4,2) DEFAULT 0,
  branch VARCHAR(50),
  year INTEGER,
  skills VARCHAR(200),
  softskills VARCHAR(200),
  full_name VARCHAR(100),
  phone VARCHAR(15),
  email VARCHAR(100),
  linkedin VARCHAR(200),
  github VARCHAR(200),
  degree VARCHAR(50),
  tenth NUMERIC(5,2),
  twelfth NUMERIC(5,2),
  backlog INTEGER DEFAULT 0,
  internships VARCHAR(500),
  projects VARCHAR(500),
  certifications VARCHAR(500),
  resume VARCHAR(200),
  location_pref VARCHAR(100),
  relocate VARCHAR(10),
  achievements VARCHAR(300),
  hobbies VARCHAR(200)
);

CREATE TABLE IF NOT EXISTS jobs (
  job_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_name VARCHAR(100),
  role VARCHAR(50),
  cgpa NUMERIC(4,2) DEFAULT 0,
  branch VARCHAR(50),
  year INTEGER,
  backlogs INTEGER DEFAULT 0,
  stipend VARCHAR(50),
  description VARCHAR(500),
  skills VARCHAR(200),
  experience VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS applications (
  application_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id BIGINT REFERENCES jobs(job_id) ON DELETE CASCADE,
  student_username VARCHAR(50) NOT NULL,
  status VARCHAR(20) DEFAULT 'PENDING',
  UNIQUE(job_id, student_username)
);

